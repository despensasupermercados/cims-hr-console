// Renders the Printshop Ops Audit mark (src/audit_brand.js markSvg) into the icon files the audit host serves and
// writes them to src/audit_brand_icons.js. Run by hand after the drawing changes:
//   node scripts/audit_icons_build.mjs
// It needs Playwright's Chromium (PLAYWRIGHT_BROWSERS_PATH, or CHROMIUM_PATH). test/audit_brand.test.js fails until the
// files are re-rendered from the drawing in audit_brand.js (SOURCE_SHA).
import { writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { createRequire } from "node:module";
import { MARK_FILES, markSource } from "../src/audit_brand.js";

const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || "playwright");

const shot = async (browser, svg, size) => {
  const page = await browser.newPage({ viewport: { width: size, height: size }, deviceScaleFactor: 1 });
  await page.setContent('<html><body style="margin:0;background:transparent">' + svg + "</body></html>");
  const png = await page.screenshot({ omitBackground: true, clip: { x: 0, y: 0, width: size, height: size } });
  await page.close();
  return png;
};

// An ICO that carries PNG images (16, 32, 48): every browser since 2010 reads it.
const ico = (pngs) => {
  const head = Buffer.alloc(6 + 16 * pngs.length);
  head.writeUInt16LE(0, 0); head.writeUInt16LE(1, 2); head.writeUInt16LE(pngs.length, 4);
  let off = head.length;
  pngs.forEach(([size, png], i) => {
    const e = 6 + 16 * i;
    head.writeUInt8(size >= 256 ? 0 : size, e); head.writeUInt8(size >= 256 ? 0 : size, e + 1);
    head.writeUInt8(0, e + 2); head.writeUInt8(0, e + 3); head.writeUInt16LE(1, e + 4); head.writeUInt16LE(32, e + 6);
    head.writeUInt32LE(png.length, e + 8); head.writeUInt32LE(off, e + 12);
    off += png.length;
  });
  return Buffer.concat([head, ...pngs.map(([, p]) => p)]);
};

const sourceSha = createHash("sha256").update(markSource()).digest("hex").slice(0, 16);
const SIZE = { PNG180: 180, PNG512: 512, PNG512M: 512, PNG32: 32, ICO16: 16, ICO48: 48 };

const browser = await chromium.launch(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {});
const r = {};
for (const k of Object.keys(MARK_FILES)) r[k] = await shot(browser, MARK_FILES[k](), SIZE[k]);
await browser.close();
const out = { PNG180: r.PNG180, PNG512: r.PNG512, PNG512M: r.PNG512M, PNG32: r.PNG32, ICO: ico([[16, r.ICO16], [32, r.PNG32], [48, r.ICO48]]) };

const lines = ["// GENERATED by scripts/audit_icons_build.mjs from markSvg() in src/audit_brand.js. Do not edit by hand.",
  "export const SOURCE_SHA = " + JSON.stringify(sourceSha) + ";"];
for (const [k, v] of Object.entries(out)) lines.push("export const " + k + " = " + JSON.stringify(v.toString("base64")) + ";");
writeFileSync(new URL("../src/audit_brand_icons.js", import.meta.url), lines.join("\n") + "\n");
console.log("wrote src/audit_brand_icons.js", Object.fromEntries(Object.entries(out).map(([k, v]) => [k, v.length])));
